export function QrCodeSvg({ value, size = 136 }: { value: string; size?: number }) {
  const matrix = useMemo(() => {
    try {
      return generateQrMatrix(value);
    } catch {
      return null;
    }
  }, [value]);

  if (!matrix) return null;
  const n = matrix.length;

  return (
    <svg
      width={size}
      height={size}
      viewBox={`0 0 ${n + 4} ${n + 4}`}
      className="rounded-lg bg-white p-1.5 border border-slate-700"
      role="img"
      aria-label={`QR code for ${value}`}
    >
      <rect width={n + 4} height={n + 4} fill="#ffffff" />
      {matrix.map((row, r) =>
        row.map((dark, c) =>
          dark ? (
            <rect key={`${r}-${c}`} x={c + 2} y={r + 2} width={1} height={1} fill="#0f172a" />
          ) : null
        )
      )}
    </svg>
  );
}

